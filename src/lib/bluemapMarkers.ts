import { promises as fs } from "fs";
import path from "path";
import { randomUUID } from "crypto";
import { runRcon } from "@/lib/rcon";

const SITE_DATA_DIR =
  process.env.SITE_DATA_DIR ?? "/var/www/mc.byjohnmichael.com/mc-site-data";
const MC_DATA_DIR = process.env.MC_DATA_DIR ?? "/opt/mc/data";
const BLUEMAP_MAPS_DIR =
  process.env.BLUEMAP_MAPS_DIR ??
  path.join(MC_DATA_DIR, "plugins", "BlueMap", "maps");

const MARKERS_FILE = "bluemap-markers.json";

export const DIMENSIONS = ["overworld", "nether", "end"] as const;
export type Dimension = (typeof DIMENSIONS)[number];

// Keys map to bluemap/web/assets/icon-<key>.svg. "pin" = BlueMap's built-in.
export const ICONS = [
  "pin",
  "home",
  "kingdom",
  "town",
  "mountain",
  "landmark",
  "river",
  "sea",
  "ruins",
  "jungle",
] as const;
export type Icon = (typeof ICONS)[number];

export type Marker = {
  id: string;
  name: string;
  x: number;
  y: number;
  z: number;
  dimension: Dimension;
  icon: Icon;
};

export type MarkerState = { markers: Marker[]; dirty: boolean };

const MAP_CONF: Record<Dimension, string> = {
  overworld: "world.conf",
  nether: "world_the_nether.conf",
  end: "world_the_end.conf",
};

const BEGIN = "# >>> managed by admin.byjohnmichael.com : BlueMap markers >>>";
const END = "# <<< managed by admin.byjohnmichael.com : BlueMap markers <<<";

/* ---------------------------------------------------------------- store --- */

async function readState(): Promise<MarkerState> {
  try {
    const raw = await fs.readFile(
      path.join(/* turbopackIgnore: true */ SITE_DATA_DIR, MARKERS_FILE),
      "utf8",
    );
    const parsed = JSON.parse(raw);
    return {
      markers: Array.isArray(parsed?.markers) ? parsed.markers : [],
      dirty: Boolean(parsed?.dirty),
    };
  } catch {
    return { markers: [], dirty: false };
  }
}

async function writeState(state: MarkerState): Promise<void> {
  await fs.mkdir(SITE_DATA_DIR, { recursive: true });
  const filePath = path.join(
    /* turbopackIgnore: true */ SITE_DATA_DIR,
    MARKERS_FILE,
  );
  const tmp = `${filePath}.${randomUUID()}.tmp`;
  await fs.writeFile(tmp, JSON.stringify(state, null, 2));
  await fs.rename(tmp, filePath);
}

export async function listMarkers(): Promise<MarkerState> {
  return readState();
}

export type MutateResult = MarkerState & { applyError?: string };

// Every add/delete immediately publishes to the live map — there's no
// separate "apply" step for the admin to remember. If the publish itself
// fails (e.g. bluemap reload can't reach RCON), the store is left dirty and
// the error rides along so the caller can surface it; the next successful
// mutation retries the publish automatically.
async function mutateAndApply(
  mutate: (state: MarkerState) => void,
): Promise<MutateResult> {
  const state = await readState();
  mutate(state);
  await writeState(state);
  const result = await applyMarkers();
  const final = await readState();
  return result.ok ? final : { ...final, applyError: result.error };
}

export async function addMarker(input: Omit<Marker, "id">): Promise<MutateResult> {
  return mutateAndApply((state) => {
    state.markers.push({ ...input, id: randomUUID() });
    state.dirty = true;
  });
}

export async function deleteMarker(id: string): Promise<MutateResult> {
  return mutateAndApply((state) => {
    const before = state.markers.length;
    state.markers = state.markers.filter((m) => m.id !== id);
    if (state.markers.length !== before) state.dirty = true;
  });
}

export async function updateMarker(
  id: string,
  input: Omit<Marker, "id">,
): Promise<MutateResult> {
  return mutateAndApply((state) => {
    const marker = state.markers.find((m) => m.id === id);
    if (!marker) return;
    Object.assign(marker, input);
    state.dirty = true;
  });
}

/* ----------------------------------------------------- config generation --- */

function hocon(s: string): string {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r?\n/g, " ");
}

function markerEntry(m: Marker): string {
  const lines = [
    `      "${m.id}": {`,
    `        type: "poi"`,
    `        label: "${hocon(m.name)}"`,
    `        position: { x: ${m.x}, y: ${m.y}, z: ${m.z} }`,
    `        detail: "${hocon(m.name)}"`,
  ];
  if (m.icon !== "pin") {
    lines.push(`        icon: "assets/icon-${m.icon}.svg"`);
    lines.push(`        anchor: { x: 20, y: 20 }`);
  }
  lines.push(`        max-distance: 10000000`);
  lines.push(`      }`);
  return lines.join("\n");
}

function generatedRegion(markers: Marker[]): string {
  const entries = markers.map(markerEntry).join("\n\n");
  const inner = entries ? `\n${entries}\n    ` : "";
  return [
    BEGIN,
    "# Generated by the admin site's marker manager. Do not edit between the",
    '# sentinel lines - changes are overwritten on the next "Apply to map".',
    "marker-sets: {",
    "  admin: {",
    '    label: "Markers"',
    "    toggleable: true",
    `    markers: {${inner}}`,
    "  }",
    "}",
    END,
  ].join("\n");
}

/** Replace an existing top-level `marker-sets { ... }` block, skipping braces
 * that appear inside `#`/`//` comments or quoted strings. */
function stripMarkerSetsBlock(conf: string): string {
  const m = /(^|\n)([ \t]*)marker-sets[ \t]*[:=]?[ \t]*\{/.exec(conf);
  if (!m) return conf;
  const lineStart = m.index + (m[1] ? 1 : 0);
  const openIdx = conf.indexOf("{", m.index);

  let depth = 0;
  let inComment = false;
  let inString = false;
  let i = openIdx;
  for (; i < conf.length; i++) {
    const c = conf[i];
    if (inComment) {
      if (c === "\n") inComment = false;
      continue;
    }
    if (inString) {
      if (c === "\\") i++;
      else if (c === '"') inString = false;
      continue;
    }
    if (c === "#" || (c === "/" && conf[i + 1] === "/")) {
      inComment = true;
      continue;
    }
    if (c === '"') {
      inString = true;
      continue;
    }
    if (c === "{") depth++;
    else if (c === "}" && --depth === 0) {
      i++;
      break;
    }
  }
  return conf.slice(0, lineStart) + conf.slice(i).replace(/^[ \t]*\n/, "");
}

function spliceRegion(conf: string, region: string): string {
  const b = conf.indexOf(BEGIN);
  const e = conf.indexOf(END);
  if (b !== -1 && e !== -1 && e > b) {
    return conf.slice(0, b) + region + conf.slice(e + END.length);
  }
  return `${stripMarkerSetsBlock(conf).replace(/\s*$/, "")}\n\n${region}\n`;
}

export async function applyMarkers(): Promise<
  { ok: true } | { ok: false; error: string }
> {
  const state = await readState();
  const byDim: Record<Dimension, Marker[]> = {
    overworld: [],
    nether: [],
    end: [],
  };
  for (const marker of state.markers) byDim[marker.dimension].push(marker);

  try {
    for (const dim of DIMENSIONS) {
      // BLUEMAP_MAPS_DIR is outside the app dir; the ignore comments keep
      // Turbopack from tracing the whole filesystem around it (as store.ts does).
      const file = path.join(
        /* turbopackIgnore: true */ BLUEMAP_MAPS_DIR,
        MAP_CONF[dim],
      );
      let conf: string;
      try {
        conf = await fs.readFile(/* turbopackIgnore: true */ file, "utf8");
      } catch {
        continue; // dimension not configured on this server
      }
      const next = spliceRegion(conf, generatedRegion(byDim[dim]));
      if (next !== conf) {
        const tmp = `${file}.${randomUUID()}.tmp`;
        await fs.writeFile(/* turbopackIgnore: true */ tmp, next);
        await fs.rename(/* turbopackIgnore: true */ tmp, file);
      }
    }
  } catch (err) {
    return {
      ok: false,
      error: `Couldn't write BlueMap config: ${(err as Error).message}`,
    };
  }

  try {
    await runRcon(["bluemap", "reload"]);
  } catch (err) {
    return {
      ok: false,
      error: `Config saved, but "bluemap reload" failed: ${(err as Error).message}`,
    };
  }

  state.dirty = false;
  await writeState(state);
  return { ok: true };
}

