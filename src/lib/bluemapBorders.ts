import { promises as fs } from "fs";
import path from "path";
import { randomUUID } from "crypto";
import { runRcon } from "@/lib/rcon";
import { DIMENSIONS, type Dimension } from "@/lib/bluemapMarkers";

const SITE_DATA_DIR =
  process.env.SITE_DATA_DIR ?? "/var/www/mc.byjohnmichael.com/mc-site-data";
const MC_DATA_DIR = process.env.MC_DATA_DIR ?? "/opt/mc/data";
const BLUEMAP_MAPS_DIR =
  process.env.BLUEMAP_MAPS_DIR ??
  path.join(MC_DATA_DIR, "plugins", "BlueMap", "maps");

const BORDERS_FILE = "bluemap-borders.json";

const BORDER_Y = 128;
const LINE_WIDTH = 4;

export type Point = { x: number; z: number };

export type Border = {
  id: string;
  name: string;
  dimension: Dimension;
  color: string; // "#rrggbb"
  points: Point[];
};

export type BorderState = { borders: Border[]; dirty: boolean };

const MAP_CONF: Record<Dimension, string> = {
  overworld: "world.conf",
  nether: "world_the_nether.conf",
  end: "world_the_end.conf",
};

const BEGIN = "# >>> managed by admin.byjohnmichael.com : BlueMap borders >>>";
const END = "# <<< managed by admin.byjohnmichael.com : BlueMap borders <<<";

/* ---------------------------------------------------------------- store --- */

async function readState(): Promise<BorderState> {
  try {
    const raw = await fs.readFile(
      path.join(/* turbopackIgnore: true */ SITE_DATA_DIR, BORDERS_FILE),
      "utf8",
    );
    const parsed = JSON.parse(raw);
    return {
      borders: Array.isArray(parsed?.borders) ? parsed.borders : [],
      dirty: Boolean(parsed?.dirty),
    };
  } catch {
    return { borders: [], dirty: false };
  }
}

async function writeState(state: BorderState): Promise<void> {
  await fs.mkdir(SITE_DATA_DIR, { recursive: true });
  const filePath = path.join(
    /* turbopackIgnore: true */ SITE_DATA_DIR,
    BORDERS_FILE,
  );
  const tmp = `${filePath}.${randomUUID()}.tmp`;
  await fs.writeFile(tmp, JSON.stringify(state, null, 2));
  await fs.rename(tmp, filePath);
}

export async function listBorders(): Promise<BorderState> {
  return readState();
}

export async function addBorder(input: Omit<Border, "id">): Promise<BorderState> {
  const state = await readState();
  state.borders.push({ ...input, id: randomUUID() });
  state.dirty = true;
  await writeState(state);
  return state;
}

export async function deleteBorder(id: string): Promise<BorderState> {
  const state = await readState();
  const before = state.borders.length;
  state.borders = state.borders.filter((b) => b.id !== id);
  if (state.borders.length !== before) state.dirty = true;
  await writeState(state);
  return state;
}

/* ----------------------------------------------------- config generation --- */

function hocon(s: string): string {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r?\n/g, " ");
}

function hexToRgb(hex: string): { r: number; g: number; b: number } {
  const m = /^#?([0-9a-fA-F]{6})$/.exec(hex);
  const h = m ? m[1] : "ffffff";
  return {
    r: parseInt(h.slice(0, 2), 16),
    g: parseInt(h.slice(2, 4), 16),
    b: parseInt(h.slice(4, 6), 16),
  };
}

function borderEntry(b: Border): string {
  const { r, g, b: blue } = hexToRgb(b.color);
  const shape = b.points.map((p) => `        { x: ${p.x}, z: ${p.z} }`).join("\n");
  const lines = [
    `      "${b.id}": {`,
    `        type: "shape"`,
    `        label: "${hocon(b.name)}"`,
    `        position: { x: ${b.points[0].x}, y: ${BORDER_Y}, z: ${b.points[0].z} }`,
    `        shape: [`,
    shape,
    `        ]`,
    `        shape-y: ${BORDER_Y}`,
    `        line-width: ${LINE_WIDTH}`,
    `        line-color: { r: ${r}, g: ${g}, b: ${blue}, a: 1.0 }`,
    // BlueMap fills with its own default color if fill-color is omitted -
    // force it fully transparent so this is a true outline-only border.
    `        fill-color: { r: 0, g: 0, b: 0, a: 0.0 }`,
    `        depth-test: false`,
    `        max-distance: 10000000`,
    `      }`,
  ];
  return lines.join("\n");
}

function generatedRegion(borders: Border[]): string {
  const entries = borders.map(borderEntry).join("\n\n");
  const inner = entries ? `\n${entries}\n    ` : "";
  return [
    BEGIN,
    "# Generated by the admin site's border manager. Do not edit between the",
    '# sentinel lines - changes are overwritten on the next "Apply to map".',
    "marker-sets: {",
    "  borders: {",
    '    label: "Borders"',
    "    toggleable: true",
    `    markers: {${inner}}`,
    "  }",
    "}",
    END,
  ].join("\n");
}

/** Replaces the managed borders region if present, otherwise appends it.
 * Unlike the markers region, this never strips a pre-existing top-level
 * `marker-sets { ... }` block - HOCON merges same-key objects across
 * occurrences, so this can coexist with the markers manager's own block. */
function spliceRegion(conf: string, region: string): string {
  const b = conf.indexOf(BEGIN);
  const e = conf.indexOf(END);
  if (b !== -1 && e !== -1 && e > b) {
    return conf.slice(0, b) + region + conf.slice(e + END.length);
  }
  return `${conf.replace(/\s*$/, "")}\n\n${region}\n`;
}

export async function applyBorders(): Promise<
  { ok: true } | { ok: false; error: string }
> {
  const state = await readState();
  const byDim: Record<Dimension, Border[]> = {
    overworld: [],
    nether: [],
    end: [],
  };
  for (const border of state.borders) byDim[border.dimension].push(border);

  try {
    for (const dim of DIMENSIONS) {
      const file = path.join(
        /* turbopackIgnore: true */ BLUEMAP_MAPS_DIR,
        MAP_CONF[dim],
      );
      let conf: string;
      try {
        conf = await fs.readFile(/* turbopackIgnore: true */ file, "utf8");
      } catch {
        continue; // dimension not configured on this server
      }
      const next = spliceRegion(conf, generatedRegion(byDim[dim]));
      if (next !== conf) {
        const tmp = `${file}.${randomUUID()}.tmp`;
        await fs.writeFile(/* turbopackIgnore: true */ tmp, next);
        await fs.rename(/* turbopackIgnore: true */ tmp, file);
      }
    }
  } catch (err) {
    return {
      ok: false,
      error: `Couldn't write BlueMap config: ${(err as Error).message}`,
    };
  }

  try {
    await runRcon(["bluemap", "reload"]);
  } catch (err) {
    return {
      ok: false,
      error: `Config saved, but "bluemap reload" failed: ${(err as Error).message}`,
    };
  }

  state.dirty = false;
  await writeState(state);
  return { ok: true };
}

